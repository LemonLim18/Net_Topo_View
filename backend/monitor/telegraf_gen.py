def _ping_targets(device_ips: List[str]) -> str:
    """ICMP ping for all devices + infrastructure VMs."""
    vm_ips = ["192.168.1.248", "192.168.1.250", "192.168.1.252", "192.168.1.3"]
    all_targets = sorted(set(device_ips + vm_ips))
    urls_str = ", ".join(f'"{ip}"' for ip in all_targets)
    return f"""
# ── ICMP Ping (all targets) ───────────────────────────────
[[inputs.ping]]
  urls     = [{urls_str}]
  count    = 3
  timeout  = 5.0
  interval = "30s"
"""


# ---------------------------------------------------------------------------
# Main generator class
# ---------------------------------------------------------------------------

class TelegrafConfigGenerator:
    """
    Builds a complete telegraf.conf from the current device inventory.

    Usage:
        gen = TelegrafConfigGenerator()
        config_text = gen.generate(devices)
        gen.write(config_text, "/etc/telegraf/telegraf.conf")
    """

    def __init__(self):
        self.influx_url    = os.getenv("INFLUXDB_URL", "http://localhost:8086")
        self.influx_token  = os.getenv("INFLUXDB_TOKEN", "")
        self.influx_org    = os.getenv("INFLUXDB_ORG", "cognishield")
        self.influx_bucket = os.getenv("INFLUXDB_BUCKET", "network_telemetry")
        self.snmp_community, self.huawei_community = _effective_snmp_communities()

    # ---- public API -------------------------------------------------------

    def generate(self, devices: Optional[List[Dict]] = None) -> str:
        """
        Generate complete telegraf.conf content.

        Parameters
        ----------
        devices : list of dict, optional
            Each dict should have at least 'ip' (str) and optionally
            'sys_descr' (str) for vendor classification.
            If None, uses CRAWL_SEEDS from env.
        """
        device_ips = self._resolve_device_ips(devices)
        if not device_ips:
            logger.warning("No device IPs found — generating minimal config")

        # Classify devices by vendor
        cisco_ips: List[str] = []
        huawei_ips: List[str] = []
        juniper_ips: List[str] = []
        all_ips: List[str] = list(device_ips.keys())

        for ip, sys_descr in device_ips.items():
            vendor = classify_vendor(ip, sys_descr, allow_static_hint=devices is None)
            if vendor == "cisco":
                cisco_ips.append(ip)
            elif vendor == "huawei":
                huawei_ips.append(ip)
            elif vendor == "juniper":
                juniper_ips.append(ip)
            # generic devices only get standard MIBs

        logger.info(
            "Telegraf config: %d devices (cisco=%d, huawei=%d, juniper=%d, generic=%d)",
            len(all_ips), len(cisco_ips), len(huawei_ips), len(juniper_ips),
            len(all_ips) - len(cisco_ips) - len(huawei_ips) - len(juniper_ips),
        )

        community = self.snmp_community
        non_huawei_ips = [ip for ip in all_ips if ip not in set(huawei_ips)]
        sections = [
            _header(self.influx_url, self.influx_token,
                    self.influx_org, self.influx_bucket),
            _snmp_system(non_huawei_ips, community),
            _cisco_cpu_mem(cisco_ips, community),
            _huawei_snmp(huawei_ips, self.huawei_community),
            _juniper_cpu_mem(juniper_ips, community),
            _interfaces(non_huawei_ips, community),
            _push_listeners(),
            _ping_targets(all_ips),
        ]

        return "\n".join(s for s in sections if s)

    def generate_device_include(self, devices: Optional[List[Dict]] = None) -> str:
        """
        Generate only dynamic device SNMP input sections for telegraf.d include usage.

        This intentionally avoids agent/output/global blocks so it can be safely
        managed as a drop-in file without clobbering the main telegraf.conf.
        """
        device_ips = self._resolve_device_ips(devices)
        cisco_ips: List[str] = []
        huawei_ips: List[str] = []
        juniper_ips: List[str] = []
        all_ips: List[str] = list(device_ips.keys())

        for ip, sys_descr in device_ips.items():
            vendor = classify_vendor(ip, sys_descr, allow_static_hint=devices is None)
            if vendor == "cisco":
                cisco_ips.append(ip)
            elif vendor == "huawei":
                huawei_ips.append(ip)
            elif vendor == "juniper":
                juniper_ips.append(ip)

        community = self.snmp_community
        non_huawei_ips = [ip for ip in all_ips if ip not in set(huawei_ips)]
        sections = [
            "# ============================================================",
            "# AUTO-GENERATED by CogniShield telegraf_gen.py",
            "# Managed dynamic device SNMP targets (do not edit manually).",
            "# ============================================================",
            _snmp_system(non_huawei_ips, community),
            _cisco_cpu_mem(cisco_ips, community),
            _huawei_snmp(huawei_ips, self.huawei_community),
            _juniper_cpu_mem(juniper_ips, community),
            _interfaces(non_huawei_ips, community),
        ]
        return "\n".join(s for s in sections if s)

    def write(self, content: str, path: str = "telegraf.conf") -> str:
        """Write the generated config to disk."""
        with open(path, "w", newline="\n", encoding="utf-8") as f:
            f.write(content)
        logger.info("Wrote telegraf config to %s (%d bytes)", path, len(content))
        return path

    def regenerate_and_write(self, devices: Optional[List[Dict]] = None,
                             path: str = "telegraf.conf") -> str:
        """One-shot: generate + write."""
        content = self.generate(devices)
        return self.write(content, path)

    # ---- helpers ----------------------------------------------------------

    def _resolve_device_ips(self, devices: Optional[List[Dict]]) -> Dict[str, str]:
        """
        Build {ip: sys_descr} mapping.

        Falls back to CRAWL_SEEDS env var if no devices supplied.
        """
        result: Dict[str, str] = {}

        if devices:
            for d in devices:
                ip = str(d.get("ip") or d.get("management_ip") or d.get("host", "")).strip()
                descr_parts = [
                    str(d.get("vendor") or "").strip(),
                    str(d.get("sys_descr") or d.get("sysDescr") or "").strip(),
                    str(d.get("description") or "").strip(),
                    str(d.get("model") or "").strip(),
                    str(d.get("os_version") or "").strip(),
                ]
                descr = " ".join(part for part in descr_parts if part).strip()
                if ip:
                    result[ip] = descr
        else:
            # Fall back to CRAWL_SEEDS
            seeds = os.getenv("CRAWL_SEEDS", "")
            for ip in seeds.split(","):
                ip = ip.strip()
                if ip:
                    result[ip] = ""

        return result


