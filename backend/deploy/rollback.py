"""
M4 Rollback Engine — Automatic Safety Net.

Handles restoring network state when a deployment fails.
Prioritises specific undo commands (generated by M3) over full snapshot restoration.
"""

import logging
from typing import Optional

from drivers.factory import DriverFactory
from drivers.base import BaseDriver
from deploy.models import Job, JobStatus, PipelineStage
from db.manager import DatabaseManager

logger = logging.getLogger("deploy.rollback")


class RollbackEngine:
    """
    Executes rollback for a failed job.

        Strategy priority:
            1. Restore the captured pre-change snapshot when available.
            2. Push ``job.rollback_config`` when targeted reverse commands exist.
    """

    def __init__(self, db_manager: DatabaseManager):
        self.db = db_manager

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def execute_rollback(
        self,
        job: Job,
        host: str,
        username: str,
        password: str,
        driver_type: str = "cisco_ios",
    ) -> bool:
        """
        Attempt to roll back a job using a fresh driver connection.

        Returns True on success, False on failure.
        """
        logger.info("Rolling back Job %s on host %s", job.id, host)
        driver: Optional[BaseDriver] = None

        try:
            driver = DriverFactory.create(
                driver_type, host=host, username=username, password=password,
            )
            driver.connect()

            # Strategy 1 — full snapshot restore
            pre_config = self._load_pre_snapshot(job)
            if pre_config:
                cmds = [
                    line for line in pre_config.strip().splitlines()
                    if line.strip()
                ]
                result = driver.push_config(cmds)
                if result.success:
                    logger.info("Rollback via snapshot restore succeeded for Job %s", job.id)
                    return True
                logger.warning(
                    "Snapshot restore failed for Job %s: %s — trying targeted reverse commands",
                    job.id, result.error_message,
                )

            # Strategy 2 — targeted undo commands
            if job.rollback_config:
                cmds = [
                    line for line in job.rollback_config.strip().splitlines()
                    if line.strip()
                ]
                result = driver.push_config(cmds)
                if result.success:
                    logger.info("Rollback via undo commands succeeded for Job %s", job.id)
                    return True
                logger.error(
                    "Undo commands also failed for Job %s: %s",
                    job.id, result.error_message,
                )

            logger.error("No rollback strategy available for Job %s", job.id)
            return False

        except Exception as exc:
            logger.exception("Rollback failed for Job %s: %s", job.id, exc)
            return False

        finally:
            if driver:
                try:
                    driver.disconnect()
                except Exception:
                    pass

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def get_rollback_commands(self, job: Job) -> Optional[str]:
        """Get the commands to reverse this job."""
        if job.rollback_config:
            return job.rollback_config
        return None

    def _load_pre_snapshot(self, job: Job) -> Optional[str]:
        """Load the pre-change config snapshot from the DB."""
        snap_id = getattr(job, "snapshot_pre_id", None)
        if not snap_id:
            return None
        try:
            with self.db._connect() as conn:
                row = conn.execute(
                    "SELECT config_text FROM config_snapshots WHERE id = ?",
                    (snap_id,),
                ).fetchone()
                return row["config_text"] if row else None
        except Exception as exc:
            logger.warning("Failed to load pre-snapshot %s: %s", snap_id, exc)
            return None
